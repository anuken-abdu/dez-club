ERR = []
def chk(t, n, what):
    if len(t) > n: ERR.append(f"{what} >{n}: {t} ({len(t)})")
    return t

def build():
    out = []
    W = out.append
    W("DEZCLUB — КОНТЕКСТНАЯ РЕКЛАМА GOOGLE ADS (ПОИСК)")
    W("Две кампании: Алматы и Астана. Только поисковая сеть, без КМС и поисковых партнёров.")
    W("Ключи только конкретные: вредитель или задача + город. Общие запросы вида «дезинфекция», «дезинфекция алматы», «сэс» исключены минус-словами.")
    W("Типы соответствия: фразовое \"…\" и точное […]. Широкое не используем.")
    W("")
    W("ОБЩИЕ НАСТРОЙКИ")
    W("Цель: потенциальные клиенты. Конверсии: клик по телефону и клик по WhatsApp (ID и метку вписать в src/data.py → GADS_ID, GADS_CALL_LABEL).")
    W("Стратегия на старте: максимум кликов с ограничением цены клика; после 15–30 конверсий — максимум конверсий.")
    W("Языки: русский, казахский. Местоположение: «Присутствие — пользователи, которые находятся в выбранных местах».")
    W("Расписание: круглосуточно, через 2 недели скорректировать по статистике звонков.")
    W("")
    for slug, c in CITIES.items():
        W("=" * 70)
        W(f"КАМПАНИЯ: DezClub — {c['nom']} — Поиск")
        W(f"Геотаргетинг: {c['nom']}, Казахстан (город)")
        W("=" * 70)
        W("")
        W("МИНУС-СЛОВА КАМПАНИИ (фразовое соответствие)")
        for n in NEG_PHRASE + c["neg"]: W(f'"{n}"')
        W("")
        W("МИНУС-СЛОВА КАМПАНИИ (точное соответствие — общие запросы)")
        for n in NEG_EXACT_BASE: W(f"[{n.format(c=c['kw'])}]")
        W("")
        W("БЫСТРЫЕ ССЫЛКИ (текст, строка описания 1, строка описания 2, конечный URL)")
        for t, d1, d2, u in SITELINKS:
            W(chk(t, 25, "sitelink")); W(chk(d1, 35, "sl d1")); W(chk(d2, 35, "sl d2")); W(f"{SITE}{u}{c['q']}"); W("")
        W("УТОЧНЕНИЯ")
        for x in CALLOUTS: W(chk(x, 25, "callout"))
        W("")
        W("СТРУКТУРИРОВАННЫЕ ОПИСАНИЯ — заголовок «Услуги»")
        for x in SNIPPET: W(chk(x, 25, "snippet"))
        W("")
        W("НОМЕР ТЕЛЕФОНА (расширение «Звонок»)")
        W("+7 700 525 01 08")
        W("")
        for name, url, kws, kws_nc, hs, ds, p1, p2 in G:
            W("-" * 70)
            W(f"ГРУППА ОБЪЯВЛЕНИЙ: {name} — {c['nom']}")
            W("-" * 70)
            W("Ключевые слова")
            for k in kws:
                k = k.format(c=c["kw"]); W(f'"{k}"'); W(f"[{k}]")
            for k in kws_nc: W(f"[{k}]")
            W("")
            W("Конечный URL")
            W(f"{SITE}{url}{c['q']}")
            W("")
            W("Отображаемый путь")
            W(chk(p1, 15, "path1")); W(chk((c["kw"] if p2 == "{p2}" else p2), 15, "path2"))
            W("")
            W("Заголовки")
            heads = [h.format(**{"in": c["inn"]}) for h in hs] + COMMON_H
            assert len(heads) == 15, name
            if len(set(heads)) != 15: ERR.append("dup headlines " + name)
            for h in heads: W(chk(h, 30, "headline"))
            W("")
            W("Описания")
            descs = [d.format(**{"in": c["inn"]}) for d in ds] + COMMON_D
            for d in descs: W(chk(d, 90, "description"))
            W("")
    return "\n".join(out) + "\n"

