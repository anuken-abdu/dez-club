ERR = []
def chk(t, n, what):
    if len(t) > n: ERR.append(f"{what} >{n}: {t} ({len(t)})")
    return t

def city_forms(slug, nom, cin):
    kw = nom.lower().replace("-", " ") if slug == "ust-kamenogorsk" else nom.lower()
    alt = ALT.get(slug, (None, []))
    return kw, cin.lower(), alt[1], (alt[0] or kw)

def landing(path, slug):
    if path == "CITY": return SITE + ("/" if slug == "almaty" else f"/goroda/{slug}/")
    return SITE + path + ("" if slug == "almaty" else f"?city={slug}")

def headlines(hs, nom, cin):
    out = []
    for h in hs + CITY_H + COMMON_H:
        t = h.format(**{"in": cin, "nom": nom})
        if len(t) > 30 and h in hs and "{in}" in h: t = h.replace(" {in}", "")  # ключ без длинного названия города
        if len(t) <= 30 and t.lower() not in {x.lower() for x in out}: out.append(t)
        if len(out) == 15: break
    return out

def descriptions(ds, cin):
    out = []
    for d in ds:
        t = d.format(**{"in": cin})
        if len(t) > 90: t = re.sub(r"\s*" + re.escape(cin), "", t)  # без города, если не влезает
        out.append(t)
    return out + COMMON_D

def xlsx(path, cols, rows):
    wb = Workbook(); ws = wb.active; ws.title = "Upload"; ws.append(cols)
    for c in ws[1]: c.font = Font(bold=True)
    for r in rows: ws.append([r.get(c, "") for c in cols])
    for i, c in enumerate(cols, 1): ws.column_dimensions[ws.cell(1, i).column_letter].width = max(14, min(48, len(c) + 4))
    wb.save(path)

